CREATE TABLE IF NOT EXISTS service_requests (
  id TEXT PRIMARY KEY,
  number TEXT UNIQUE NOT NULL,
  customer_id TEXT NOT NULL REFERENCES customers(id),
  contact_name TEXT,
  contact_email TEXT,
  title TEXT NOT NULL,
  description TEXT,
  category TEXT DEFAULT 'general',
  priority TEXT DEFAULT 'medium',
  status TEXT DEFAULT 'open',
  assigned_to TEXT REFERENCES users(id),
  source TEXT DEFAULT 'crm',
  sla_due_at TEXT,
  resolved_at TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS assets (
  id TEXT PRIMARY KEY,
  customer_id TEXT REFERENCES customers(id),
  asset_tag TEXT UNIQUE,
  name TEXT NOT NULL,
  category TEXT,
  manufacturer TEXT,
  model TEXT,
  serial_number TEXT,
  location TEXT,
  status TEXT DEFAULT 'active',
  installed_at TEXT,
  warranty_until TEXT,
  next_service_at TEXT,
  notes TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS work_orders (
  id TEXT PRIMARY KEY,
  number TEXT UNIQUE NOT NULL,
  customer_id TEXT REFERENCES customers(id),
  project_id TEXT REFERENCES projects(id),
  service_request_id TEXT REFERENCES service_requests(id),
  asset_id TEXT REFERENCES assets(id),
  title TEXT NOT NULL,
  description TEXT,
  priority TEXT DEFAULT 'medium',
  status TEXT DEFAULT 'scheduled',
  assigned_employee_id TEXT REFERENCES employees(id),
  scheduled_start TEXT,
  scheduled_end TEXT,
  check_in_at TEXT,
  check_in_lat REAL,
  check_in_lng REAL,
  check_out_at TEXT,
  check_out_lat REAL,
  check_out_lng REAL,
  resolution TEXT,
  customer_signature TEXT,
  completed_at TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS work_order_updates (
  id TEXT PRIMARY KEY,
  work_order_id TEXT NOT NULL REFERENCES work_orders(id) ON DELETE CASCADE,
  update_type TEXT NOT NULL,
  note TEXT,
  document_id TEXT REFERENCES documents(id),
  actor_id TEXT REFERENCES users(id),
  metadata TEXT DEFAULT '{}',
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS time_entries (
  id TEXT PRIMARY KEY,
  employee_id TEXT NOT NULL REFERENCES employees(id),
  work_order_id TEXT REFERENCES work_orders(id),
  project_id TEXT REFERENCES projects(id),
  started_at TEXT NOT NULL,
  ended_at TEXT,
  minutes INTEGER DEFAULT 0,
  entry_type TEXT DEFAULT 'work',
  approved_by TEXT REFERENCES users(id),
  approved_at TEXT,
  notes TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
